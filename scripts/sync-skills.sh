#!/bin/sh
# Copies the five kit skills from their sibling repos into skills/ and records
# the commit each came from in skills/SOURCES.md. Run from the repo root.
set -eu
GH="${GH_DIR:-$HOME/Documents/Github}"
cd "$(dirname "$0")/.."
: > skills/SOURCES.md.tmp
echo "# Bundled kit skills" >> skills/SOURCES.md.tmp
echo "" >> skills/SOURCES.md.tmp
echo "Generated by scripts/sync-skills.sh. Edit upstream, then re-sync." >> skills/SOURCES.md.tmp
echo "" >> skills/SOURCES.md.tmp
echo "| Skill | Repo | Commit |" >> skills/SOURCES.md.tmp
echo "|---|---|---|" >> skills/SOURCES.md.tmp
sync() { # name repo src
  rm -rf "skills/$1"; mkdir -p "skills/$1"
  rsync -a --exclude .DS_Store "$3/" "skills/$1/"
  sha=$(git -C "$GH/$2" rev-parse --short HEAD)
  echo "| \`$1\` | [hemal08ce094/$2](https://github.com/hemal08ce094/$2) | $sha |" >> skills/SOURCES.md.tmp
}
sync design-skills-swiftui DesignSkillsSwiftUI "$GH/DesignSkillsSwiftUI/skill/design-skills-swiftui"
sync impeccable-swiftui ImpeccableSwiftUI "$GH/ImpeccableSwiftUI/skill/impeccable-swiftui"
cp "$GH/ImpeccableSwiftUI/LICENSE" skills/impeccable-swiftui/LICENSE
cp "$GH/ImpeccableSwiftUI/NOTICE.md" skills/impeccable-swiftui/NOTICE.md
sync thinking-orbs-swiftui ThinkingOrbsSwiftUI "$GH/ThinkingOrbsSwiftUI/skill/thinking-orbs-swiftui"
sync bot-avatars-swiftui BotAvatarsSwiftUI "$GH/BotAvatarsSwiftUI/skill/bot-avatars-swiftui"
# DrawablySwiftUI keeps its skill outside the repo; prefer an in-repo copy if one appears.
if [ -d "$GH/DrawablySwiftUI/skill/drawably-swiftui" ]; then
  sync drawably-swiftui DrawablySwiftUI "$GH/DrawablySwiftUI/skill/drawably-swiftui"
else
  sync drawably-swiftui DrawablySwiftUI "$HOME/.claude/skills/drawably-swiftui"
fi
mv skills/SOURCES.md.tmp skills/SOURCES.md
echo "synced $(ls -d skills/*/ | wc -l | tr -d ' ') skills"
